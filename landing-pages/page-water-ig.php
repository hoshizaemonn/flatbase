    function extractOrderId(element) {
      try {
        if (!element || !element.textContent) {
          return 'order_' + Date.now();
        }
        
        // 方法1: テキストから抽出
        const orderIdMatch = element.textContent.match(/注文[番号|ID|番]:?\s*([A-Z0-9-]+)/i);
        if (orderIdMatch && orderIdMatch[1]) {
          return orderIdMatch[1];
        }
        
        // 方法2: data属性から取得
        if (element.dataset) {
          const dataOrderId = element.dataset.orderId || element.dataset.transactionId;
          if (dataOrderId) {
            return dataOrderId;
          }
        }
        
        // 方法3: 親要素から取得
        if (element.closest) {
          const parentOrderId = element.closest('[data-order-id], [data-transaction-id]');
          if (parentOrderId && parentOrderId.dataset) {
            return parentOrderId.dataset.orderId || parentOrderId.dataset.transactionId || 'order_' + Date.now();
          }
        }
        
      } catch (e) {
        console.error('注文ID抽出エラー:', e);
      }
      
      // デフォルト: タイムスタンプベースのID
      return 'order_' + Date.now();
    }
    
