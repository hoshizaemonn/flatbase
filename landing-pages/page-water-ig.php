      // スマホの連絡先からも取得できるようにtelを設定（+81は後で削除）
      input.setAttribute('autocomplete', 'tel');
      // inputmodeを設定してスマホで数字キーボードを表示
      input.setAttribute('inputmode', 'tel');
      
      // +81や+を自動的に削除する処理
      function removeInternationalPrefix(value) {
        // +81で始まる場合、+81を削除
        if (value.startsWith('+81')) {
          value = value.replace(/^\+81/, '');
          // 先頭の0を追加（日本の電話番号は0から始まる）
          if (value.length > 0 && !value.startsWith('0')) {
            value = '0' + value;
          }
        }
        // +で始まる場合、+を削除
        else if (value.startsWith('+')) {
          value = value.replace(/^\+/, '');
        }
        return value;
      }
      
      // フォーカス時に+81が入っている場合は削除
      input.addEventListener('focus', function(e) {
        let value = e.target.value;
        if (value.includes('+81') || value.startsWith('+')) {
          value = removeInternationalPrefix(value);
          e.target.value = value;
        }
      });
      
      // 電話番号の自動フォーマット（ハイフン自動挿入）+ +81削除
      input.addEventListener('input', function(e) {
        let value = e.target.value;
        
        // +81や+を削除
        value = removeInternationalPrefix(value);
        
        // 数字以外を削除
        value = value.replace(/[^\d]/g, '');
        
        if (value.length > 0) {
          if (value.length <= 3) {
            value = value;
          } else if (value.length <= 7) {
            value = value.slice(0, 3) + '-' + value.slice(3);
          } else if (value.length <= 11) {
            value = value.slice(0, 3) + '-' + value.slice(3, 7) + '-' + value.slice(7);
          } else {
            value = value.slice(0, 3) + '-' + value.slice(3, 7) + '-' + value.slice(7, 11);
          }
          e.target.value = value;
        }
      });
      
