          return 0;
        }
        
        // 方法1: テキストから抽出（「1,980円」「¥1,980」「1980円」など）
        const amountMatches = [
          element.textContent.match(/([0-9,]+)円/),
          element.textContent.match(/¥([0-9,]+)/),
          element.textContent.match(/([0-9,]+)yen/i)
        ];
        
        for (let i = 0; i < amountMatches.length; i++) {
          if (amountMatches[i] && amountMatches[i][1]) {
            return parseFloat(amountMatches[i][1].replace(/,/g, '')) || 0;
          }
        }
        
        // 方法2: data属性から取得
        if (element.dataset) {
          const dataAmount = element.dataset.amount || element.dataset.total || element.dataset.value;
          if (dataAmount) {
            return parseFloat(dataAmount) || 0;
          }
        }
        
        // 方法3: 親要素から取得
        if (element.closest) {
          const parentAmount = element.closest('[data-amount], [data-total], [data-value]');
          if (parentAmount && parentAmount.dataset) {
            const amount = parentAmount.dataset.amount || parentAmount.dataset.total || parentAmount.dataset.value;
            if (amount) {
              return parseFloat(amount) || 0;
            }
          }
        }
        
      } catch (e) {
        console.error('金額抽出エラー:', e);
      }
      
      return 0;
    }
    
    // ========================================
    // 9. 初期化
    // ========================================
    function init() {
      try {
        // UTMパラメータを保存
        saveUtmParameters();
        
        // 購入フォーム到達を追跡
        trackHashChange();
        
        // 購入完了を追跡
        trackIframePurchase();
        
        console.log('✅ GA4購入イベント測定が開始されました');
      } catch (e) {
        console.error('GA4初期化エラー:', e);
      }
    }
    
    // ページ読み込み時に実行
    if (document.readyState === 'loading') {
      document.addEventListener('DOMContentLoaded', init);
    } else {
      // DOMContentLoadedイベントが既に発生している場合は即座に実行
      setTimeout(init, 100);
    }
    
    // window.onloadでも実行（すべてのリソース読み込み後）
    if (window.addEventListener) {
      window.addEventListener('load', function() {
        setTimeout(init, 500);
      });
    }
    
  } catch (globalError) {
    console.error('GA4スクリプト全体エラー:', globalError);
  }
})();
