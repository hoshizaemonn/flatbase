              // 住所入力欄にフォーカスを移動（ユーザーが確認・修正できるように）
              addressInput.focus();
            } else {
              console.log('[FEO] 郵便番号が見つかりませんでした:', postalCode);
            }
          })
          .catch(function(error) {
            console.error('[FEO] 住所取得エラー:', error);
          });
      }
    });
    
